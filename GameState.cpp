#include "GameState.h"
using namespace std;
#include <iostream>

void GameState::GameStart(Player* player, Enemy* enemy)
{
	system("CLS");
	srand(time(0));
	int whosTurn = rand() % 2 + 1;


	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "---------------------------------------------------- BATTLE HAS STARTED ------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;

	do {
		if (whosTurn == 1)
		{
			player->takeTurn(enemy);
		}

		if (whosTurn == 2)
		{
			enemy->taketurn(enemy, player);
		}

		


		

	}
	while (player->health > 0 && enemy->health > 0);
	if (enemy->health > 0) 
	{
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "------------------------------------------------------You Won The Fight-------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		displayDead(player);
	}
	else 
	{
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "-----------------------------------------------------You Lost The Fight-------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		displayDead(player);
	}



	
}

void GameState::displayDead(Player* player)
{
	cout << "Enemies Slain: " << player->killed << endl;
}
