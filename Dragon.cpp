Dragon::Dragon()
{
	health = 200;
	damage = 20;
}

Dragon::~Dragon()
{
}

float Dragon::attack(float damage, Player* player, NightCycle* cycle) {
	srand(time(0));
	int randomNumber = rand() % 2 + 1;
    float multiplier = 0;
    if (cycle->calcDay(cycle) == true) {
        cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
        cout << "----------------------------------------------- DRAGON IS ENRANGED ----------------------------------------------------" << endl;
        cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
        multiplier = 1.5;
        cycle++;
    }
    else {
        multiplier = 1;
    }

	if (randomNumber == 1)
	{
		return damage * multiplier;
	}
	else
	{
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "-------------------------------------------------- Attack Missed -------------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		return false;
	}
}

