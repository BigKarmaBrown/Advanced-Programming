#include "GameState.h"
using namespace std;
#include <iostream>

void GameState::GameStart(Player* player, Enemy* enemy)
{
	system("CLS");
	srand(static_cast<unsigned int>(time(0)));
	int whosTurn = rand() % 2 + 1;


	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "---------------------------------------------------- BATTLE HAS STARTED ------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	system("Pause");
	system("CLS");
	enemy->displayPicture();
	while (true){

		if (player->health <= 0 || enemy->health <= 0) {
			displayWinner(player, enemy);
			break;
		}
		else if (whosTurn == 1)
		{
			player->takeTurn(player, enemy);
			system("Pause");
			system("CLS");
			enemy->displayPicture();
			whosTurn = 2;
		}
	
		else if (whosTurn == 2) {
			enemy->taketurn(enemy, player);
			system("Pause");
			system("CLS");
			enemy->displayPicture();
			whosTurn = 1;
		}
	
	}

}
void GameState::displayWinner(Player* player, Enemy* enemy) {
	if (enemy->health <= 0)
	{
		player->killed++;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "------------------------------------------------------You Won The Fight-------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		
		displayDead(player);
		enemy = NULL;
		return;
	}
	else if (player->health <= 0)
	{
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "-----------------------------------------------------You Lost The Fight-------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		
		displayDead(player);
		player = NULL;
		return;
	}
}

void GameState::displayDead(Player* player)
{
	cout << "Enemies Slain: " << player->killed << endl;
}
