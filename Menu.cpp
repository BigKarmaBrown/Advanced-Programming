void Menu::chooseOpponent(Player* player, Enemy* enemy, GameState*& gameState, NightCycle* cycle, LinkedListMoves* moves)
{
	system("CLS");
	delete gameState;
	player->health = player->maxHealth;
	gameState = new GameState(moves);
	if (gameState->playerRanBool == true) {
			cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "--------------------------------------------------- Ran Succesfully ----------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		system("Pause");
	}
	string choice;
	
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "-------------------------------------------------- ENEMY SELECTION -----------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "-------------------------------------------------- 1: Goblin -----------------------------------------------------------" << endl;
	cout << "-------------------------------------------------- 2: Dragon -----------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	cout << "-------------------------------------------------- 3: Return -----------------------------------------------------------" << endl;
	cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
	
	
	
	

	cin >> choice;
	if (choice == "QUIT" || choice == "Quit" || choice == "3" || choice == "3: Quit")
	{
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "-------------------------------------------------- returning -----------------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		system("pause");
		delete player;
		system("CLS");
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		cout << "----------------------------------------------- Player deleted ---------------------------------------------------------" << endl;
		cout << "------------------------------------------------------------------------------------------------------------------------" << endl;
		system("pause");
		return;
	}
	else if (choice == "1" || choice == "Goblin" || choice == "goblin" || choice == "Gob" || choice == "gob") {
		enemy = new Goblin();
		cycle = new NightCycle();
		cout << "-------------------------------------------------- Goblin  Selected ----------------------------------------------------" << endl;
		gameState->playerRanBool = false;
		system("pause");
		
		GameState::battleResult result = gameState->GameStart(player, enemy, gameState, cycle, moves);
		if (result == GameState::battleResult::playerRan || result == GameState::battleResult::playerLose || result == GameState::battleResult::playerWin)
		{
			delete enemy;
			enemy = nullptr;
			//Free the allocated memory using the keyword delete. 
			// Set the pointer to null to avoid dangling pointers.
			chooseOpponent(player, enemy, gameState, cycle, moves);
			return;
		}
	
	}
	else if (choice == "2" || choice == "Dragon" || choice == "dragon" || choice == "Drag" || choice == "drag") {
		enemy = new Dragon();
		cycle = new NightCycle();
		gameState->playerRanBool = false;
		cout << "-------------------------------------------------- Dragon  Selected ----------------------------------------------------" << endl;
		system("pause");
		GameState::battleResult result = gameState->GameStart(player, enemy, gameState, cycle, moves);
		if (result == GameState::battleResult::playerRan || result == GameState::battleResult::playerLose || result == GameState::battleResult::playerWin)
		{
			delete enemy;
			enemy = nullptr;
			chooseOpponent(player, enemy, gameState, cycle, moves);
			return;
		}
	
			
		
	}
	
	else {
		cout << "Invalid Input, Please try again!" << endl;
		return;
	}
}

